CREATE TABLE IF NOT EXISTS order_file_asset
(
    order_file_asset_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT                   NOT NULL,
    file_asset_id         BIGINT                   NOT NULL,
    plate_number          INTEGER                  NOT NULL DEFAULT 1,
    plate_name            VARCHAR(180),
    material              VARCHAR(60),
    color_hex             VARCHAR(30),
    infill_percent        INTEGER,
    supports              BOOLEAN,
    scale_x               DOUBLE PRECISION         NOT NULL DEFAULT 1.0,
    scale_y               DOUBLE PRECISION         NOT NULL DEFAULT 1.0,
    scale_z               DOUBLE PRECISION         NOT NULL DEFAULT 1.0,
    is_multi_color        BOOLEAN                  NOT NULL DEFAULT FALSE,
    painting_instructions TEXT,
    guid                  VARCHAR(36)              NOT NULL,
    status                VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user           VARCHAR(100),
    update_dt             TIMESTAMP WITH TIME ZONE,
    update_user           VARCHAR(100),

    CONSTRAINT fk_order_file_asset_order
        FOREIGN KEY (order_id)
            REFERENCES orders (order_id)
            ON DELETE CASCADE,

    CONSTRAINT fk_order_file_asset_file
        FOREIGN KEY (file_asset_id)
            REFERENCES file_asset (file_asset_id)
            ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_order_file_asset_order_id
    ON order_file_asset (order_id);

CREATE INDEX IF NOT EXISTS idx_order_file_asset_file_asset_id
    ON order_file_asset (file_asset_id);

INSERT INTO order_file_asset (
    order_id,
    file_asset_id,
    plate_number,
    plate_name,
    scale_x,
    scale_y,
    scale_z,
    is_multi_color,
    guid,
    status,
    create_dt,
    create_user,
    update_dt,
    update_user
)
SELECT
    o.order_id,
    o.file_asset_id,
    1,
    COALESCE(fa.name, 'Mesa 1'),
    1.0,
    1.0,
    1.0,
    FALSE,
    gen_random_uuid()::varchar,
    COALESCE(o.status, 'A'),
    COALESCE(o.create_dt, CURRENT_TIMESTAMP),
    COALESCE(o.create_user, 'SYSTEM'),
    o.update_dt,
    o.update_user
FROM orders o
LEFT JOIN file_asset fa ON fa.file_asset_id = o.file_asset_id
WHERE o.file_asset_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM order_file_asset ofa
      WHERE ofa.order_id = o.order_id
        AND ofa.file_asset_id = o.file_asset_id
  );
