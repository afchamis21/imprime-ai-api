CREATE TABLE chat_participant_state (
    chat_id            UUID                     NOT NULL REFERENCES chat (chat_id) ON DELETE CASCADE,
    user_guid          VARCHAR(36)              NOT NULL,
    last_read_at       TIMESTAMP WITH TIME ZONE,
    last_email_sent_at TIMESTAMP WITH TIME ZONE,
    pending_since      TIMESTAMP WITH TIME ZONE,
    next_notify_at     TIMESTAMP WITH TIME ZONE,
    pending_count      INT                      NOT NULL DEFAULT 0,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (chat_id, user_guid)
);

CREATE INDEX idx_chat_participant_pending
    ON chat_participant_state (next_notify_at)
    WHERE next_notify_at IS NOT NULL;

CREATE INDEX idx_chat_participant_user
    ON chat_participant_state (user_guid);

CREATE TABLE email_notification_log (
    email_notification_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id                  VARCHAR(128)             NOT NULL UNIQUE,
    category                  VARCHAR(50)              NOT NULL,
    template_name             VARCHAR(120)             NOT NULL,
    recipient_email           VARCHAR(255)             NOT NULL,
    subject                   VARCHAR(255)             NOT NULL,
    status                    VARCHAR(30)              NOT NULL,
    provider                  VARCHAR(40),
    provider_message_id       VARCHAR(180),
    attempts                  INT                      NOT NULL DEFAULT 0,
    last_error                TEXT,
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at                   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_email_notification_log_status_created
    ON email_notification_log (status, created_at);

CREATE TABLE user_notification_preference (
    user_notification_preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                         BIGINT                   NOT NULL UNIQUE REFERENCES users (user_id),
    chat_digest_enabled             BOOLEAN                  NOT NULL DEFAULT TRUE,
    reviews_enabled                 BOOLEAN                  NOT NULL DEFAULT TRUE,
    marketing_enabled               BOOLEAN                  NOT NULL DEFAULT TRUE,
    guid                            VARCHAR(36)              NOT NULL UNIQUE,
    status                          VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt                       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user                     VARCHAR(100),
    update_dt                       TIMESTAMP WITH TIME ZONE,
    update_user                     VARCHAR(100)
);
