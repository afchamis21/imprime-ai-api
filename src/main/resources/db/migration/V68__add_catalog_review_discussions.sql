ALTER TABLE review ADD COLUMN image_urls JSONB NOT NULL DEFAULT '[]';

CREATE TABLE review_reply (
    review_reply_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES review (review_id),
    author_user_id BIGINT NOT NULL REFERENCES users (user_id),
    comment TEXT NOT NULL,
    image_urls JSONB NOT NULL DEFAULT '[]',
    guid VARCHAR(36) NOT NULL UNIQUE,
    status VARCHAR(5) NOT NULL DEFAULT 'A',
    create_dt TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user VARCHAR(100),
    update_dt TIMESTAMP WITH TIME ZONE,
    update_user VARCHAR(100)
);

CREATE INDEX idx_review_reply_thread ON review_reply (review_id, status, create_dt, review_reply_id);

CREATE TABLE review_like (
    review_id BIGINT NOT NULL REFERENCES review (review_id),
    user_id BIGINT NOT NULL REFERENCES users (user_id),
    PRIMARY KEY (review_id, user_id)
);
