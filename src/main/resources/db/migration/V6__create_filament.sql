CREATE TABLE filament
(
    filament_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    BIGINT          NOT NULL,
    asset_id      BIGINT,
    stock         NUMERIC(10, 2)   NOT NULL,
    filament_type VARCHAR(100)   NOT NULL,
    description   TEXT,
    status        VARCHAR(5),
    create_dt     TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    create_user   VARCHAR(100),
    update_dt     TIMESTAMP WITH TIME ZONE,
    update_user   VARCHAR(100),

    CONSTRAINT fk_filament_company
        FOREIGN KEY (company_id)
            REFERENCES company (company_id)
                ON DELETE CASCADE,

    CONSTRAINT fk_filament_asset
        FOREIGN KEY (asset_id)
            REFERENCES asset (asset_id)
                ON DELETE SET NULL
);

CREATE INDEX idx_filament_company_id
    ON filament (company_id);

CREATE INDEX idx_filament_asset_id
    ON filament (asset_id);