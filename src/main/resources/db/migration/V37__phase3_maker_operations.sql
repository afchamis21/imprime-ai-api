    ADD COLUMN IF NOT EXISTS name                    VARCHAR(120),
    ADD COLUMN IF NOT EXISTS brand                   VARCHAR(80)    NOT NULL DEFAULT 'Genérico',
    ADD COLUMN IF NOT EXISTS material                VARCHAR(30),
    ADD COLUMN IF NOT EXISTS color_name              VARCHAR(60)    NOT NULL DEFAULT 'Neutro',
    ADD COLUMN IF NOT EXISTS color_hex               VARCHAR(7)     NOT NULL DEFAULT '#64748b',
    ADD COLUMN IF NOT EXISTS initial_weight_grams    NUMERIC(10, 2) NOT NULL DEFAULT 1000.00,
    ADD COLUMN IF NOT EXISTS cost_per_kg             NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    ADD COLUMN IF NOT EXISTS diameter_mm             NUMERIC(5, 2)  NOT NULL DEFAULT 1.75,
    ADD COLUMN IF NOT EXISTS low_stock_threshold_grams NUMERIC(10, 2) NOT NULL DEFAULT 250.00,
    ADD COLUMN IF NOT EXISTS humidity_percent        INTEGER,
    ADD COLUMN IF NOT EXISTS spool_location          VARCHAR(100),
    ADD COLUMN IF NOT EXISTS notes                   VARCHAR(500),
    ADD COLUMN IF NOT EXISTS version                 BIGINT         NOT NULL DEFAULT 0;

UPDATE filament
SET name = COALESCE(NULLIF(TRIM(description), ''), filament_type)
WHERE name IS NULL;

UPDATE filament
SET material = CASE
    WHEN UPPER(TRIM(filament_type)) IN ('PLA', 'PETG', 'ABS', 'TPU', 'ASA', 'NYLON', 'RESIN', 'CARBON_FIBER', 'OTHER')
        THEN UPPER(TRIM(filament_type))
    ELSE 'PLA'
END
WHERE material IS NULL;

ALTER TABLE filament
    ALTER COLUMN name SET NOT NULL,
    ALTER COLUMN material SET NOT NULL;

