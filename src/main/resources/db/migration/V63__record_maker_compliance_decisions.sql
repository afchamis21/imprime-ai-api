CREATE TABLE maker_order_compliance
(
    maker_order_compliance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (order_id),
    company_id BIGINT NOT NULL REFERENCES company (company_id),
    actor_user_id BIGINT NOT NULL REFERENCES users (user_id),
    action VARCHAR(20) NOT NULL CHECK (action IN ('QUOTE', 'START', 'REFUSE')),
    legal_document_id BIGINT REFERENCES legal_document (legal_document_id),
    reason VARCHAR(30) CHECK (reason IN ('COPYRIGHT', 'PROHIBITED_ITEM')),
    acted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX maker_order_unique_refusal ON maker_order_compliance (order_id, company_id)
    WHERE action = 'REFUSE';
