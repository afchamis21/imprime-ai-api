CREATE TABLE address
(
    address_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    country         VARCHAR(100)  NOT NULL,
    state           VARCHAR(100),
    city            VARCHAR(100),
    zip_code        VARCHAR(20),
    address_line_1  VARCHAR(255)  NOT NULL,
    address_line_2  VARCHAR(255),
    default_address BOOL,
    status          VARCHAR(5),
    create_dt       TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    create_user     VARCHAR(100),
    update_dt       TIMESTAMP WITH TIME ZONE,
    update_user     VARCHAR(100),

    CONSTRAINT fk_address_user
        FOREIGN KEY (user_id)
            REFERENCES users (user_id)
            ON DELETE CASCADE
);

CREATE INDEX idx_address_user_id
    ON address (user_id);

ALTER TABLE users
    ADD CONSTRAINT fk_users_primary_address
        FOREIGN KEY (primary_address_id)
            REFERENCES address (address_id);