ALTER TABLE users
    ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE user_security_token (
    user_security_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT                   NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    purpose                VARCHAR(32)              NOT NULL,
    token_hash             VARCHAR(128)             NOT NULL UNIQUE,
    target_email           VARCHAR(255)             NOT NULL,
    expires_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at                TIMESTAMP WITH TIME ZONE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_user_security_token_lookup
    ON user_security_token (user_id, purpose, used_at);

CREATE INDEX idx_user_security_token_expires
    ON user_security_token (expires_at);
