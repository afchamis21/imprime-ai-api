CREATE TABLE IF NOT EXISTS maker_quote_history
(
    maker_quote_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id             BIGINT         NOT NULL,
    title                  VARCHAR(180)   NOT NULL,
    client_name            VARCHAR(120),
    quote_status           VARCHAR(20)    NOT NULL DEFAULT 'DRAFT',
    quantity               INTEGER        NOT NULL DEFAULT 1,
    unit_price             NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    final_price_total      NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    production_cost_total  NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    estimated_profit_total NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    input_snapshot         JSONB          NOT NULL DEFAULT '{}'::jsonb,
    settings_snapshot      JSONB          NOT NULL DEFAULT '{}'::jsonb,
    result_snapshot        JSONB          NOT NULL DEFAULT '{}'::jsonb,
    guid                   VARCHAR(36)    NOT NULL UNIQUE,
    status                 VARCHAR(5)     NOT NULL DEFAULT 'A',
    create_dt              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user            VARCHAR(100),
    update_dt              TIMESTAMP WITH TIME ZONE,
    update_user            VARCHAR(100),

    CONSTRAINT fk_maker_quote_history_company
        FOREIGN KEY (company_id) REFERENCES company (company_id) ON DELETE CASCADE,
    CONSTRAINT chk_mqh_quote_status
        CHECK (quote_status IN ('DRAFT', 'SENT', 'APPROVED', 'REJECTED')),
    CONSTRAINT chk_mqh_quantity
        CHECK (quantity >= 1)
);

CREATE INDEX IF NOT EXISTS idx_maker_quote_history_company_status_dt
    ON maker_quote_history (company_id, status, create_dt DESC);
