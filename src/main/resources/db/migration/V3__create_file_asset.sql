CREATE TABLE file_asset
(
    file_asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT          NOT NULL,
    asset_url     VARCHAR(1000),
    name          VARCHAR(255)   NOT NULL,
    asset_type    VARCHAR(10) NOT NULL,
    status        VARCHAR(5),
    create_dt     TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    create_user   VARCHAR(100),
    update_dt     TIMESTAMP WITH TIME ZONE,
    update_user   VARCHAR(100),

    CONSTRAINT fk_file_asset_user
        FOREIGN KEY (user_id)
            REFERENCES users (user_id)
            ON DELETE CASCADE
);

CREATE INDEX idx_file_asset_user_id
    ON file_asset (user_id);