CREATE TABLE order_status
(
    order_status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    status_cd       VARCHAR(30)  NOT NULL,
    status_date     TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status          VARCHAR(5),
    create_dt       TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    create_user     VARCHAR(100),
    update_dt       TIMESTAMP WITH TIME ZONE,
    update_user     VARCHAR(100),

    CONSTRAINT fk_order_status_order
        FOREIGN KEY (order_id)
            REFERENCES orders (order_id)
                ON DELETE CASCADE,

    CONSTRAINT fk_order_status_lkup
        FOREIGN KEY (status_cd)
            REFERENCES order_status_lkup (code)
);