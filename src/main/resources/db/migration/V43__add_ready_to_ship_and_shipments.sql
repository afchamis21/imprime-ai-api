CREATE TABLE order_shipment (
    order_shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    external_order_id VARCHAR(120) UNIQUE,
    service_id INTEGER NOT NULL,
    carrier_name VARCHAR(120),
    service_name VARCHAR(120),
    tracking_code VARCHAR(120),
    tracking_status VARCHAR(80),
    shipment_status VARCHAR(30) NOT NULL DEFAULT 'SELECTED',
    package_number INTEGER NOT NULL DEFAULT 1,
    quoted_price NUMERIC(10, 2),
    package_snapshot JSONB,
    label_url TEXT,
    label_expires_at TIMESTAMP WITH TIME ZONE,
    last_error TEXT,
    guid VARCHAR(36) NOT NULL UNIQUE,
    create_dt TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user VARCHAR(100),
    update_dt TIMESTAMP WITH TIME ZONE,
    update_user VARCHAR(100),
    status VARCHAR(5) NOT NULL DEFAULT 'A'
);

CREATE TABLE order_shipping_quote (
    order_shipping_quote_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES users (user_id),
    vendor_id BIGINT NOT NULL REFERENCES company (company_id),
    delivery_address_id BIGINT NOT NULL REFERENCES address (address_id),
    service_id INTEGER NOT NULL,
    service_name VARCHAR(120) NOT NULL,
    carrier_name VARCHAR(120),
    quote_price NUMERIC(10, 2) NOT NULL,
    delivery_days INTEGER,
    snapshot JSONB NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_order_id BIGINT REFERENCES orders (order_id),
    guid VARCHAR(36) NOT NULL UNIQUE,
    create_dt TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user VARCHAR(100),
    update_dt TIMESTAMP WITH TIME ZONE,
    update_user VARCHAR(100),
    status VARCHAR(5) NOT NULL DEFAULT 'A'
);

CREATE INDEX idx_order_shipping_quote_owner
    ON order_shipping_quote (buyer_id, vendor_id, expires_at, status);

CREATE TABLE melhor_envio_credential (
    credential_id SMALLINT PRIMARY KEY,
    encrypted_access_token TEXT NOT NULL,
    encrypted_refresh_token TEXT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_order_shipment_order_status
    ON order_shipment (order_id, status, shipment_status);

CREATE INDEX idx_order_shipment_tracking
    ON order_shipment (tracking_code)
    WHERE tracking_code IS NOT NULL;
