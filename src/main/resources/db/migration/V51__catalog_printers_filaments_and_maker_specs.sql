-- 1. Tabela de Catálogo Fixo de Impressoras 3D
CREATE TABLE IF NOT EXISTS printer_catalog
(
    printer_catalog_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand                      VARCHAR(100)             NOT NULL,
    model_name                 VARCHAR(150)             NOT NULL,
    slug                       VARCHAR(220)             NOT NULL UNIQUE,
    build_volume_x_mm          NUMERIC(8, 2)            NOT NULL,
    build_volume_y_mm          NUMERIC(8, 2)            NOT NULL,
    build_volume_z_mm          NUMERIC(8, 2)            NOT NULL,
    is_enclosed                BOOLEAN                  NOT NULL DEFAULT FALSE,
    max_nozzle_temp_c          INTEGER                  NOT NULL,
    max_bed_temp_c             INTEGER                  NOT NULL,
    default_nozzle_mm          NUMERIC(5, 3)            NOT NULL DEFAULT 0.400,
    filament_diameter_mm       NUMERIC(4, 2)                     DEFAULT 1.75,
    max_print_speed_mm_s       INTEGER,
    max_power_watts_110v       INTEGER,
    max_power_watts_220v       INTEGER,
    input_voltage              VARCHAR(40)              NOT NULL DEFAULT 'BIVOLT_110_220V',
    connectivity_methods       JSONB                    NOT NULL DEFAULT '[]'::jsonb,
    weight_kg                  NUMERIC(6, 2),
    technology                 VARCHAR(20)              NOT NULL DEFAULT 'FDM',
    kinematics                 VARCHAR(30),
    extruder_type              VARCHAR(30),
    supports_multicolor        BOOLEAN                  NOT NULL DEFAULT FALSE,
    multicolor_system_name     VARCHAR(80),
    max_color_slots            INTEGER                  NOT NULL DEFAULT 1,
    avg_power_watts            INTEGER,
    active_chamber_heating     BOOLEAN                  NOT NULL DEFAULT FALSE,
    max_chamber_temp_c         INTEGER,
    min_layer_height_mm        NUMERIC(5, 3),
    max_layer_height_mm        NUMERIC(5, 3),
    max_acceleration_mm_s2     INTEGER,
    supported_nozzle_sizes_mm  JSONB                    NOT NULL DEFAULT '[0.4]'::jsonb,
    hardened_nozzle_default    BOOLEAN                  NOT NULL DEFAULT FALSE,
    has_auto_bed_leveling      BOOLEAN                  NOT NULL DEFAULT TRUE,
    has_filament_runout_sensor BOOLEAN                  NOT NULL DEFAULT TRUE,
    has_camera                 BOOLEAN                  NOT NULL DEFAULT FALSE,
    has_air_filtration         BOOLEAN                  NOT NULL DEFAULT FALSE,
    release_year               INTEGER,
    estimated_price_brl        NUMERIC(12, 2),
    image_url                  VARCHAR(1000),
    official_specs_url         VARCHAR(500),
    notes                      TEXT,
    guid                       VARCHAR(36)              NOT NULL UNIQUE,
    status                     VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt                  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user                VARCHAR(100),
    update_dt                  TIMESTAMP WITH TIME ZONE,
    update_user                VARCHAR(100),

    CONSTRAINT chk_pc_build_volume_positive CHECK (
        build_volume_x_mm > 0 AND build_volume_y_mm > 0 AND build_volume_z_mm > 0
    ),
    CONSTRAINT chk_pc_temps_non_negative CHECK (
        max_nozzle_temp_c >= 0 AND max_bed_temp_c >= 0
    ),
    CONSTRAINT chk_pc_max_color_slots CHECK (max_color_slots >= 1)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_printer_catalog_brand_model_active
    ON printer_catalog (LOWER(brand), LOWER(model_name))
    WHERE status = 'A';

CREATE INDEX IF NOT EXISTS idx_printer_catalog_status_brand
    ON printer_catalog (status, brand);

CREATE INDEX IF NOT EXISTS idx_printer_catalog_flags
    ON printer_catalog (status, is_enclosed, supports_multicolor);

-- 2. Tabela Associativa Normalizada de Materiais Suportados por Impressora
CREATE TABLE IF NOT EXISTS printer_catalog_material
(
    printer_catalog_id BIGINT      NOT NULL REFERENCES printer_catalog (printer_catalog_id) ON DELETE CASCADE,
    material           VARCHAR(30) NOT NULL,
    PRIMARY KEY (printer_catalog_id, material)
);

CREATE INDEX IF NOT EXISTS idx_printer_catalog_material_mat
    ON printer_catalog_material (material, printer_catalog_id);

-- 3. Tabela de Catálogo Global de Perfis de Filamentos (estilo 3dfilamentprofiles.com)
CREATE TABLE IF NOT EXISTS filament_catalog
(
    filament_catalog_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand                      VARCHAR(100)             NOT NULL,
    line_name                  VARCHAR(120)             NOT NULL,
    slug                       VARCHAR(240)             NOT NULL UNIQUE,
    material                   VARCHAR(30)              NOT NULL,
    material_subtype           VARCHAR(60),
    color_name                 VARCHAR(80)              NOT NULL,
    color_hex                  VARCHAR(7)               NOT NULL,
    secondary_color_hex        VARCHAR(7),
    finish_type                VARCHAR(30)              NOT NULL DEFAULT 'STANDARD',
    diameter_mm                NUMERIC(4, 2)            NOT NULL DEFAULT 1.75,
    density_g_cm3              NUMERIC(5, 3)            NOT NULL DEFAULT 1.240,
    default_spool_weight_g     INTEGER                  NOT NULL DEFAULT 1000,
    spool_type                 VARCHAR(30)                       DEFAULT 'PLASTIC',
    nozzle_temp_min_c          INTEGER                  NOT NULL,
    nozzle_temp_max_c          INTEGER                  NOT NULL,
    nozzle_temp_recommended_c  INTEGER,
    bed_temp_min_c             INTEGER                  NOT NULL,
    bed_temp_max_c             INTEGER                  NOT NULL,
    bed_temp_recommended_c     INTEGER,
    max_volumetric_speed_mm3_s NUMERIC(5, 2),
    pressure_advance_k         NUMERIC(5, 4),
    transmission_distance_mm   NUMERIC(5, 2),
    drying_temp_c              INTEGER,
    drying_time_hours          INTEGER,
    requires_enclosure         BOOLEAN                  NOT NULL DEFAULT FALSE,
    requires_hardened_nozzle   BOOLEAN                  NOT NULL DEFAULT FALSE,
    ams_compatible             BOOLEAN                  NOT NULL DEFAULT TRUE,
    hygroscopic_level          VARCHAR(15)              NOT NULL DEFAULT 'LOW',
    shore_hardness             VARCHAR(15),
    reference_price_brl_per_kg NUMERIC(10, 2),
    sku                        VARCHAR(80),
    gtin_ean                   VARCHAR(32),
    purchase_url               VARCHAR(500),
    image_url                  VARCHAR(1000),
    notes                      TEXT,
    guid                       VARCHAR(36)              NOT NULL UNIQUE,
    status                     VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt                  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user                VARCHAR(100),
    update_dt                  TIMESTAMP WITH TIME ZONE,
    update_user                VARCHAR(100),

    CONSTRAINT chk_fc_nozzle_temps CHECK (
        nozzle_temp_min_c >= 0 AND nozzle_temp_max_c >= nozzle_temp_min_c
    ),
    CONSTRAINT chk_fc_bed_temps CHECK (
        bed_temp_min_c >= 0 AND bed_temp_max_c >= bed_temp_min_c
    )
);

CREATE INDEX IF NOT EXISTS idx_filament_catalog_status_material
    ON filament_catalog (status, material);

CREATE INDEX IF NOT EXISTS idx_filament_catalog_brand
    ON filament_catalog (status, brand);

CREATE INDEX IF NOT EXISTS idx_filament_catalog_color_hex
    ON filament_catalog (color_hex);

-- 4. Extensões no Perfil Técnico do Maker (company)
ALTER TABLE company
    ADD COLUMN IF NOT EXISTS primary_printer_catalog_id BIGINT REFERENCES printer_catalog (printer_catalog_id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS supports_multicolor        BOOLEAN       NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS max_multicolor_slots       INTEGER       NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS offers_post_processing     BOOLEAN       NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS offers_painting            BOOLEAN       NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS offers_cad_modeling        BOOLEAN       NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS supports_express_orders    BOOLEAN       NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS min_layer_height_mm        NUMERIC(5, 3),
    ADD COLUMN IF NOT EXISTS technical_notes            VARCHAR(500);

CREATE INDEX IF NOT EXISTS idx_company_primary_printer_catalog_id
    ON company (primary_printer_catalog_id);

-- Backfill seguro de flags em company a partir de capabilities e slots AMS existentes
UPDATE company c
SET supports_multicolor = TRUE,
    max_multicolor_slots = GREATEST(COALESCE(c.max_multicolor_slots, 1), 4)
WHERE (c.capabilities IS NOT NULL AND c.capabilities @> '["MULTICOLOR_AMS"]'::jsonb)
   OR EXISTS (
       SELECT 1
       FROM asset a
       JOIN printer_ams_slot pas ON pas.asset_id = a.asset_id AND pas.status = 'A'
       WHERE a.company_id = c.company_id
         AND a.status = 'A'
   );

UPDATE company
SET offers_painting = TRUE
WHERE capabilities IS NOT NULL
  AND capabilities @> '["PAINTING"]'::jsonb;

UPDATE company
SET offers_post_processing = TRUE
WHERE capabilities IS NOT NULL
  AND capabilities @> '["POST_PROCESSING"]'::jsonb;

UPDATE company
SET offers_cad_modeling = TRUE
WHERE capabilities IS NOT NULL
  AND capabilities @> '["MODELING"]'::jsonb;

-- 5. Extensões na Frota de Impressoras do Maker (asset)
ALTER TABLE asset
    ADD COLUMN IF NOT EXISTS printer_catalog_id         BIGINT REFERENCES printer_catalog (printer_catalog_id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS supports_multicolor        BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS multicolor_slots           INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS is_enclosed_override       BOOLEAN,
    ADD COLUMN IF NOT EXISTS supported_materials_override JSONB;

CREATE INDEX IF NOT EXISTS idx_asset_printer_catalog_id
    ON asset (printer_catalog_id);

UPDATE asset a
SET supports_multicolor = TRUE,
    multicolor_slots    = GREATEST(COALESCE(a.multicolor_slots, 1), 4)
WHERE EXISTS (
    SELECT 1
    FROM printer_ams_slot pas
    WHERE pas.asset_id = a.asset_id
      AND pas.status = 'A'
);

-- 6. Vínculo opcional do inventário do Maker com o catálogo global de filamentos
ALTER TABLE filament
    ADD COLUMN IF NOT EXISTS filament_catalog_id BIGINT REFERENCES filament_catalog (filament_catalog_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_filament_catalog_id
    ON filament (filament_catalog_id);

