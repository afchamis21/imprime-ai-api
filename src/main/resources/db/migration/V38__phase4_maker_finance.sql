CREATE TABLE maker_finance_transaction
(
    finance_transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id             BIGINT         NOT NULL,
    order_id               BIGINT,
    transaction_date       DATE           NOT NULL,
    transaction_type       VARCHAR(30)    NOT NULL,
    title                  VARCHAR(200)   NOT NULL,
    reference              VARCHAR(100),
    category               VARCHAR(80),
    amount                 NUMERIC(12, 2) NOT NULL,
    transaction_status     VARCHAR(20)    NOT NULL,
    pix_key_type           VARCHAR(20),
    pix_key_masked         VARCHAR(140),
    idempotency_key        VARCHAR(100) UNIQUE,
    guid                   VARCHAR(36)    NOT NULL UNIQUE,
    status                 VARCHAR(5)     NOT NULL DEFAULT 'A',
    create_dt              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user            VARCHAR(100),
    update_dt              TIMESTAMP WITH TIME ZONE,
    update_user            VARCHAR(100),

    CONSTRAINT fk_maker_fin_tx_company
        FOREIGN KEY (company_id) REFERENCES company (company_id) ON DELETE CASCADE,
    CONSTRAINT fk_maker_fin_tx_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
);

CREATE INDEX idx_maker_fin_tx_company_status_dt
    ON maker_finance_transaction (company_id, status, transaction_date DESC, create_dt DESC);

CREATE INDEX idx_maker_fin_tx_company_type
    ON maker_finance_transaction (company_id, transaction_type, transaction_status, status);
