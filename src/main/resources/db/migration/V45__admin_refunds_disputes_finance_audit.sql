CREATE INDEX idx_designer_fin_tx_user_status
    ON designer_finance_transaction (designer_user_id, status, transaction_date DESC);

CREATE INDEX idx_designer_fin_tx_type_status
    ON designer_finance_transaction (transaction_type, transaction_status, status);

CREATE TABLE admin_audit_log
(
    audit_log_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id BIGINT       NOT NULL REFERENCES users (user_id),
    admin_email   VARCHAR(255) NOT NULL,
    admin_name    VARCHAR(200) NOT NULL,
    action        VARCHAR(60)  NOT NULL,
    target_type   VARCHAR(40)  NOT NULL,
    target_guid   VARCHAR(64),
    reason        TEXT,
    before_state  JSONB,
    after_state   JSONB,
    ip_address    VARCHAR(64),
    user_agent    VARCHAR(500),
    guid          VARCHAR(36)  NOT NULL UNIQUE,
    status        VARCHAR(5)   NOT NULL DEFAULT 'A',
    create_dt     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user   VARCHAR(100),
    update_dt     TIMESTAMP WITH TIME ZONE,
    update_user   VARCHAR(100)
);

CREATE INDEX idx_admin_audit_admin_dt
    ON admin_audit_log (admin_user_id, create_dt DESC);

CREATE INDEX idx_admin_audit_action_dt
    ON admin_audit_log (action, create_dt DESC);

CREATE INDEX idx_admin_audit_target
    ON admin_audit_log (target_type, target_guid);
