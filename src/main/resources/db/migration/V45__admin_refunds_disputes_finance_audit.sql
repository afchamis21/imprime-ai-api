CREATE TABLE refund_request
(
    refund_request_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             BIGINT         NOT NULL REFERENCES orders (order_id),
    requested_by_user_id BIGINT         NOT NULL REFERENCES users (user_id),
    refund_type          VARCHAR(20)    NOT NULL,
    requested_amount     NUMERIC(12, 2) NOT NULL,
    approved_amount      NUMERIC(12, 2),
    refund_status        VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    reason               TEXT           NOT NULL,
    evidence_urls        JSONB          DEFAULT '[]'::jsonb,
    admin_notes          TEXT,
    rejection_reason     TEXT,
    stripe_refund_id     VARCHAR(120),
    reviewed_by_user_id  BIGINT         REFERENCES users (user_id),
    reviewed_at          TIMESTAMP WITH TIME ZONE,
    guid                 VARCHAR(36)    NOT NULL UNIQUE,
    status               VARCHAR(5)     NOT NULL DEFAULT 'A',
    create_dt            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user          VARCHAR(100),
    update_dt            TIMESTAMP WITH TIME ZONE,
    update_user          VARCHAR(100)
);

CREATE INDEX idx_refund_request_order
    ON refund_request (order_id, status);

CREATE INDEX idx_refund_request_status
    ON refund_request (refund_status, status, create_dt DESC);

ALTER TABLE support_ticket
    ADD COLUMN IF NOT EXISTS is_dispute BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    ADD COLUMN IF NOT EXISTS assigned_admin_id BIGINT REFERENCES users (user_id),
    ADD COLUMN IF NOT EXISTS resolution_notes TEXT,
    ADD COLUMN IF NOT EXISTS resolved_at TIMESTAMP WITH TIME ZONE;

CREATE INDEX IF NOT EXISTS idx_support_ticket_dispute_status
    ON support_ticket (is_dispute, ticket_status, priority, status);

ALTER TABLE support_ticket_message
    ADD COLUMN IF NOT EXISTS attachments JSONB DEFAULT '[]'::jsonb;

ALTER TABLE maker_finance_transaction
    ADD COLUMN IF NOT EXISTS processed_by_user_id BIGINT REFERENCES users (user_id),
    ADD COLUMN IF NOT EXISTS processed_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS failure_reason TEXT;

CREATE TABLE designer_finance_transaction
(
    designer_finance_transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
