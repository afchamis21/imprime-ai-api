CREATE TABLE asset
(
    asset_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id       BIGINT        NOT NULL,
    model            VARCHAR(255) NOT NULL,
    make             VARCHAR(255) NOT NULL,
    manufacture_year INTEGER     NOT NULL,
    tray_width       NUMERIC(10, 2),
    tray_depth       NUMERIC(10, 2),
    status           VARCHAR(5),
    create_dt        TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP  NOT NULL,
    create_user      VARCHAR(100),
    update_dt        TIMESTAMP WITH TIME ZONE,
    update_user      VARCHAR(100),

    CONSTRAINT fk_asset_company
        FOREIGN KEY (company_id)
            REFERENCES company (company_id)
                ON DELETE CASCADE
);

CREATE INDEX idx_asset_company_id
    ON asset (company_id);