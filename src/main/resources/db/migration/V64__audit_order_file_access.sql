CREATE TABLE order_file_access
(
    order_file_access_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (order_id),
    file_asset_id BIGINT NOT NULL REFERENCES file_asset (file_asset_id),
    actor_user_id BIGINT NOT NULL REFERENCES users (user_id),
    accessed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX order_file_access_by_order ON order_file_access (order_id, accessed_at);
