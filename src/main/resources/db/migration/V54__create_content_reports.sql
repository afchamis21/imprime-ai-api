-- V54: Sistema de denúncias (reports) para Produtos, Modelos 3D e Makers
-- ============================================================================

CREATE TABLE content_report
(
    content_report_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol            VARCHAR(40)  NOT NULL UNIQUE,
    reporter_user_id    BIGINT       NOT NULL REFERENCES users (user_id),
    target_type         VARCHAR(20)  NOT NULL,
    target_id           BIGINT       NOT NULL,
    target_guid         VARCHAR(64)  NOT NULL,
    target_name         VARCHAR(200) NOT NULL,
    reason              VARCHAR(40)  NOT NULL,
    description         TEXT         NOT NULL,
    evidence_urls       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    report_status       VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    priority            VARCHAR(20)  NOT NULL DEFAULT 'MEDIUM',
    assigned_admin_id   BIGINT       REFERENCES users (user_id),
    resolution_notes    TEXT,
    reviewed_by_user_id BIGINT       REFERENCES users (user_id),
    reviewed_at         TIMESTAMP WITH TIME ZONE,
    guid                VARCHAR(36)  NOT NULL UNIQUE,
    status              VARCHAR(5)   NOT NULL DEFAULT 'A',
    create_dt           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user         VARCHAR(100),
    update_dt           TIMESTAMP WITH TIME ZONE,
    update_user         VARCHAR(100)
);

CREATE INDEX idx_content_report_status_dt
    ON content_report (report_status, status, create_dt DESC);

CREATE INDEX idx_content_report_target
    ON content_report (target_type, target_id, status);

CREATE INDEX idx_content_report_reporter
    ON content_report (reporter_user_id, target_type, target_id, report_status, status);

