CREATE TABLE ip_notice_followup
(
    ip_notice_followup_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_report_id BIGINT NOT NULL REFERENCES content_report (content_report_id),
    message VARCHAR(4000) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ip_notice_followup_by_report ON ip_notice_followup (content_report_id, submitted_at);
