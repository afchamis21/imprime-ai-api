CREATE TABLE legal_document
(
    legal_document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type VARCHAR(32) NOT NULL CHECK (document_type IN ('terms', 'privacy', 'prohibited-items', 'print-declaration')),
    version VARCHAR(40) NOT NULL,
    locale VARCHAR(10) NOT NULL,
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    document_status VARCHAR(12) NOT NULL CHECK (document_status IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
    effective_at TIMESTAMPTZ,
    CHECK (document_status = 'DRAFT' OR effective_at IS NOT NULL),
    UNIQUE (document_type, version, locale)
);

CREATE UNIQUE INDEX legal_document_published
    ON legal_document (document_type, locale) WHERE document_status = 'PUBLISHED';

