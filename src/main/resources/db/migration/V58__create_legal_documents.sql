CREATE FUNCTION preserve_legal_document_content() RETURNS TRIGGER
LANGUAGE plpgsql AS $function$
BEGIN
    IF ROW(NEW.document_type, NEW.version, NEW.locale, NEW.title, NEW.body)
        IS DISTINCT FROM ROW(OLD.document_type, OLD.version, OLD.locale, OLD.title, OLD.body) THEN
        RAISE EXCEPTION 'Create a new legal document version to change its content';
    END IF;
    RETURN NEW;
END;
$function$;

CREATE TRIGGER legal_document_content_immutable
    BEFORE UPDATE ON legal_document
    FOR EACH ROW EXECUTE FUNCTION preserve_legal_document_content();
