-- 1. Catálogo Global de Módulos de Orçamento
CREATE TABLE IF NOT EXISTS quote_settings
(
    quote_settings_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(50)              NOT NULL UNIQUE,
    title                  VARCHAR(100)             NOT NULL,
    description            VARCHAR(500)             NOT NULL,
    quote_type             VARCHAR(30)              NOT NULL,
    phase_order            INTEGER                  NOT NULL,
    execution_order        INTEGER                  NOT NULL,
    quote_calculator_class VARCHAR(255)             NOT NULL,
    default_enabled        BOOLEAN                  NOT NULL DEFAULT TRUE,
    can_disable            BOOLEAN                  NOT NULL DEFAULT TRUE,
    allow_quote_override   BOOLEAN                  NOT NULL DEFAULT TRUE,
    mutual_exclusion_group VARCHAR(50),
    default_config         JSONB                    NOT NULL DEFAULT '{}'::jsonb,
    ui_schema              JSONB                    NOT NULL DEFAULT '{}'::jsonb,
    guid                   VARCHAR(36)              NOT NULL UNIQUE,
    status                 VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user            VARCHAR(100),
    update_dt              TIMESTAMP WITH TIME ZONE,
    update_user            VARCHAR(100),

    CONSTRAINT chk_qs_quote_type CHECK (
        quote_type IN ('BASE_COST', 'COST_MODIFIER', 'PROFIT', 'DISCOUNT_PROMOTION', 'FEE_TAX')
    ),
    CONSTRAINT chk_qs_phase_order CHECK (phase_order > 0),
    CONSTRAINT chk_qs_execution_order CHECK (execution_order >= 0)
);

CREATE INDEX IF NOT EXISTS idx_quote_settings_status_order
    ON quote_settings (status, phase_order, execution_order);

