-- 3. Transição da tabela maker_quote_settings (V48 -> V50)
DROP INDEX IF EXISTS uq_maker_quote_settings_active_company;
ALTER TABLE IF EXISTS maker_quote_settings RENAME TO maker_quote_settings_v48_legacy;

CREATE TABLE IF NOT EXISTS maker_quote_settings
(
    maker_quote_settings_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id              BIGINT                   NOT NULL,
    quote_settings_id       BIGINT                   NOT NULL,
    enabled                 BOOLEAN                  NOT NULL DEFAULT TRUE,
    execution_order         INTEGER                  NOT NULL,
    config                  JSONB                    NOT NULL DEFAULT '{}'::jsonb,
    guid                    VARCHAR(36)              NOT NULL UNIQUE,
    status                  VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user             VARCHAR(100),
    update_dt               TIMESTAMP WITH TIME ZONE,
    update_user             VARCHAR(100),

    CONSTRAINT fk_mqs_v50_company
        FOREIGN KEY (company_id) REFERENCES company (company_id) ON DELETE CASCADE,
    CONSTRAINT fk_mqs_v50_quote_settings
        FOREIGN KEY (quote_settings_id) REFERENCES quote_settings (quote_settings_id) ON DELETE RESTRICT,
    CONSTRAINT chk_mqs_v50_execution_order CHECK (execution_order >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_maker_quote_settings_active_company_module
    ON maker_quote_settings (company_id, quote_settings_id)
    WHERE status = 'A';

CREATE INDEX IF NOT EXISTS idx_maker_quote_settings_company_status
    ON maker_quote_settings (company_id, status);

-- 4. Migração automática dos registros existentes da V48 para módulos JSONB
INSERT INTO maker_quote_settings (
    company_id,
    quote_settings_id,
    enabled,
    execution_order,
    config,
    guid,
    status,
    create_dt,
    create_user,
    update_dt,
    update_user
)
SELECT
    legacy.company_id,
    qs.quote_settings_id,
    CASE
        WHEN qs.code = 'PROFIT_MARKUP' THEN (legacy.pricing_strategy = 'MARKUP')
        WHEN qs.code = 'PROFIT_MARGIN' THEN (legacy.pricing_strategy = 'MARGIN_ON_PRICE')
        ELSE qs.default_enabled
    END AS enabled,
    qs.execution_order,
    CASE qs.code
        WHEN 'MATERIAL' THEN qs.default_config
        WHEN 'POWER' THEN jsonb_build_object(
            'kwhRate', COALESCE(comp.kwh_rate, 0.92),
            'defaultPowerWatts', legacy.default_power_watts
        )
        WHEN 'DEPRECIATION' THEN jsonb_build_object(
            'depreciationMode', legacy.depreciation_mode,
            'hourlyDepreciationRate', COALESCE(comp.hourly_depreciation_rate, 2.50),
            'defaultMachinePrice', legacy.default_machine_price,
            'defaultMachineLifespanHours', legacy.default_machine_lifespan_hours,
            'defaultMaintenanceHourlyCost', legacy.default_maintenance_hourly_cost
        )
        WHEN 'LABOR' THEN jsonb_build_object(
            'laborHourlyRate', legacy.labor_hourly_rate,
            'defaultLaborMinutes', 15,
            'requireExplicitToggleOnQuote', TRUE
        )
        WHEN 'PACKAGING' THEN jsonb_build_object(
            'fixedPackagingCost', legacy.fixed_packaging_cost
        )
        WHEN 'EXTRA_COSTS' THEN qs.default_config
        WHEN 'FAILURE_RESERVE' THEN jsonb_build_object(
            'failureRatePercent', legacy.failure_rate_percent,
            'applyOn', 'DIRECT_PRINT_COST'
        )
        WHEN 'PROFIT_MARKUP' THEN jsonb_build_object(
            'profitMarginPercent',
            CASE WHEN legacy.pricing_strategy = 'MARKUP' THEN legacy.default_profit_margin_percent ELSE 50.00 END
        )
        WHEN 'PROFIT_MARGIN' THEN jsonb_build_object(
            'profitMarginPercent',
            CASE WHEN legacy.pricing_strategy = 'MARGIN_ON_PRICE' THEN legacy.default_profit_margin_percent ELSE 35.00 END
        )
        WHEN 'PROMOTION_DISCOUNT' THEN qs.default_config
        WHEN 'ADDITIONAL_FEE' THEN jsonb_build_object(
            'additionalFeePercent', legacy.additional_fee_percent,
            'feeLabel', 'Maquininha / Marketplace'
        )
        ELSE qs.default_config
    END AS config,
    gen_random_uuid()::text,
    legacy.status,
    legacy.create_dt,
    COALESCE(legacy.create_user, 'FLYWAY_V50_MIGRATION'),
    legacy.update_dt,
    'FLYWAY_V50_MIGRATION'
FROM maker_quote_settings_v48_legacy legacy
JOIN company comp ON comp.company_id = legacy.company_id
CROSS JOIN quote_settings qs
WHERE legacy.status = 'A';

DROP TABLE IF EXISTS maker_quote_settings_v48_legacy;
