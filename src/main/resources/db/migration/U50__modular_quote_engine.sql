-- ============================================================================
-- U50: Rollback do Motor de Orçamento 3D Modular para estrutura V48
-- ============================================================================

CREATE TABLE IF NOT EXISTS maker_quote_settings_v48_rollback
(
    maker_quote_settings_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id                      BIGINT                   NOT NULL,
    default_power_watts             INTEGER                  NOT NULL DEFAULT 300,
    depreciation_mode               VARCHAR(30)              NOT NULL DEFAULT 'FIXED_HOURLY',
    default_machine_price           NUMERIC(12, 2)           NOT NULL DEFAULT 3500.00,
    default_machine_lifespan_hours  INTEGER                  NOT NULL DEFAULT 3000,
    default_maintenance_hourly_cost NUMERIC(10, 2)           NOT NULL DEFAULT 0.50,
    failure_rate_percent            NUMERIC(5, 2)            NOT NULL DEFAULT 10.00,
    labor_hourly_rate               NUMERIC(10, 2)           NOT NULL DEFAULT 35.00,
    fixed_packaging_cost            NUMERIC(10, 2)           NOT NULL DEFAULT 5.00,
    default_profit_margin_percent   NUMERIC(6, 2)            NOT NULL DEFAULT 50.00,
    additional_fee_percent          NUMERIC(5, 2)            NOT NULL DEFAULT 0.00,
    pricing_strategy                VARCHAR(30)              NOT NULL DEFAULT 'MARKUP',
    guid                            VARCHAR(36)              NOT NULL UNIQUE,
    status                          VARCHAR(5)               NOT NULL DEFAULT 'A',
    create_dt                       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user                     VARCHAR(100),
    update_dt                       TIMESTAMP WITH TIME ZONE,
    update_user                     VARCHAR(100),
    CONSTRAINT fk_maker_quote_settings_company FOREIGN KEY (company_id) REFERENCES company (company_id) ON DELETE CASCADE
);

INSERT INTO maker_quote_settings_v48_rollback (
    company_id, default_power_watts, depreciation_mode, default_machine_price,
    default_machine_lifespan_hours, default_maintenance_hourly_cost,
    failure_rate_percent, labor_hourly_rate, fixed_packaging_cost,
    default_profit_margin_percent, additional_fee_percent, pricing_strategy,
    guid, status, create_user
)
SELECT
    mqs.company_id,
    COALESCE((MAX(CASE WHEN qs.code = 'POWER' THEN mqs.config ->> 'defaultPowerWatts' END))::INTEGER, 300),
    COALESCE(MAX(CASE WHEN qs.code = 'DEPRECIATION' THEN mqs.config ->> 'depreciationMode' END), 'FIXED_HOURLY'),
    COALESCE((MAX(CASE WHEN qs.code = 'DEPRECIATION' THEN mqs.config ->> 'defaultMachinePrice' END))::NUMERIC(12, 2), 3500.00),
    COALESCE((MAX(CASE WHEN qs.code = 'DEPRECIATION' THEN mqs.config ->> 'defaultMachineLifespanHours' END))::INTEGER, 3000),
    COALESCE((MAX(CASE WHEN qs.code = 'DEPRECIATION' THEN mqs.config ->> 'defaultMaintenanceHourlyCost' END))::NUMERIC(10, 2), 0.50),
    COALESCE((MAX(CASE WHEN qs.code = 'FAILURE_RESERVE' THEN mqs.config ->> 'failureRatePercent' END))::NUMERIC(5, 2), 10.00),
    COALESCE((MAX(CASE WHEN qs.code = 'LABOR' THEN mqs.config ->> 'laborHourlyRate' END))::NUMERIC(10, 2), 35.00),
    COALESCE((MAX(CASE WHEN qs.code = 'PACKAGING' THEN mqs.config ->> 'fixedPackagingCost' END))::NUMERIC(10, 2), 5.00),
    COALESCE(
        MAX(CASE WHEN qs.code = 'PROFIT_MARGIN' AND mqs.enabled THEN (mqs.config ->> 'profitMarginPercent')::NUMERIC(6, 2) END),
        MAX(CASE WHEN qs.code = 'PROFIT_MARKUP' AND mqs.enabled THEN (mqs.config ->> 'profitMarginPercent')::NUMERIC(6, 2) END),
        50.00
    ),
    COALESCE((MAX(CASE WHEN qs.code = 'ADDITIONAL_FEE' THEN mqs.config ->> 'additionalFeePercent' END))::NUMERIC(5, 2), 0.00),
    CASE
        WHEN BOOL_OR(qs.code = 'PROFIT_MARGIN' AND mqs.enabled) THEN 'MARGIN_ON_PRICE'
        ELSE 'MARKUP'
    END,
    gen_random_uuid()::text,
    'A',
    'FLYWAY_U50_ROLLBACK'
FROM maker_quote_settings mqs
JOIN quote_settings qs ON qs.quote_settings_id = mqs.quote_settings_id
WHERE mqs.status = 'A'
GROUP BY mqs.company_id;

DROP INDEX IF EXISTS idx_maker_quote_settings_company_status;
DROP INDEX IF EXISTS uq_maker_quote_settings_active_company_module;
DROP TABLE IF EXISTS maker_quote_settings;
ALTER TABLE maker_quote_settings_v48_rollback RENAME TO maker_quote_settings;

CREATE UNIQUE INDEX IF NOT EXISTS uq_maker_quote_settings_active_company
    ON maker_quote_settings (company_id)
    WHERE status = 'A';

DROP INDEX IF EXISTS idx_quote_settings_status_order;
DROP TABLE IF EXISTS quote_settings;
